#!/usr/bin/env python3
"""
Rebuild embedding ledgers from disk, and verify the models share a corpus.

WHY A REBUILD IS NEEDED
    clip336 was produced by two processes (workers 0-3 and 4-7) writing to
    separate directories that were later merged. The .npy files all came
    across, but progress.json did not - it still describes only the half that
    owned that directory, so it undercounts by ~4M. The vectors are the real
    output; the ledger is derived, so the fix is to regenerate it from what is
    actually on disk rather than trust either half's record.

    --rebuild walks <model>/worker_*/*.npy, reads only the array headers, and
    rewrites progress.json + run_summary.json to match reality.

WHY THE COMPARISON MATTERS
    Cross-model retrieval is only meaningful if every model embedded the same
    images. --compare checks that, at two levels:

      shard sets   which shards each model covers
      row counts   for shards they share, do they hold the same number of rows

    Matching row counts per shard is strong evidence of identical image sets:
    the images in a shard are fixed, and the traversal is deterministic, so a
    difference in count would mean a difference in content.

Both modes read .npy headers only (never the arrays), in parallel.
"""

import json
import argparse
import multiprocessing as mp
from pathlib import Path
from datetime import datetime
from typing import Dict, Tuple, List

import numpy as np

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_EMBED_ROOT = REPO_ROOT / "result/embeddings_image"


def log(msg: str) -> None:
    print(f"[{datetime.now():%Y-%m-%d %H:%M:%S}] {msg}", flush=True)


def npy_rows(path_s: str) -> Tuple[str, int, int]:
    """(relative key, rows, dim) from the .npy header alone."""
    p = Path(path_s)
    try:
        a = np.load(path_s, mmap_mode="r")
        return f"{p.parent.name}/{p.stem}", int(a.shape[0]), int(a.shape[1])
    except Exception:
        return f"{p.parent.name}/{p.stem}", -1, -1


def scan_model(model_dir: Path, workers: int) -> Dict[str, Tuple[int, int]]:
    files = [str(p) for p in sorted(model_dir.glob("worker_*/*.npy"))]
    if not files:
        return {}
    with mp.Pool(processes=workers) as pool:
        rows = pool.map(npy_rows, files, chunksize=16)
    return {k: (n, d) for k, n, d in rows}


def cmd_rebuild(model_dir: Path, workers: int) -> int:
    log(f"scanning {model_dir} ...")
    info = scan_model(model_dir, workers)
    if not info:
        log("no .npy files found"); return 1

    bad = [k for k, (n, _) in info.items() if n < 0]
    if bad:
        log(f"WARNING: {len(bad)} unreadable .npy files, e.g. {bad[:3]}")

    total = sum(n for n, _ in info.values() if n > 0)
    dims = {d for _, d in info.values() if d > 0}
    # A shard is complete only if its names sidecar agrees with the array.
    missing_names, mismatched = [], []
    for k in info:
        w, s = k.split("/")
        nj = model_dir / w / f"{s}.names.json"
        if not nj.exists():
            missing_names.append(k)
        else:
            try:
                if len(json.load(open(nj))) != info[k][0]:
                    mismatched.append(k)
            except Exception:
                mismatched.append(k)

    per_worker: Dict[str, int] = {}
    for k, (n, _) in info.items():
        per_worker[k.split("/")[0]] = per_worker.get(k.split("/")[0], 0) + max(n, 0)

    log(f"  shards          : {len(info)}")
    log(f"  total vectors   : {total:,}")
    log(f"  embedding dims  : {sorted(dims)}")
    log(f"  missing names   : {len(missing_names)}")
    log(f"  name/row mismatch: {len(mismatched)}")
    for w in sorted(per_worker, key=lambda x: int(x.split('_')[1])):
        log(f"    {w:<10} {per_worker[w]:>9,}")

    if missing_names or mismatched:
        log("REFUSING to write a ledger over inconsistent shards - fix these first")
        return 1

    prev = {}
    pp = model_dir / "progress.json"
    if pp.exists():
        try:
            prev = json.load(open(pp))
        except Exception:
            prev = {}

    progress = {
        "completed_tars": sorted(f"{k}.tar" for k in info),
        "total_images": total,
        "total_failed": int(prev.get("total_failed", 0)),
        "rebuilt_from_disk_at": datetime.now().isoformat(),
        "note": "regenerated by finalize.py from the .npy files present; "
                "supersedes per-process ledgers from a split run",
    }
    tmp = pp.with_suffix(".json.tmp")
    json.dump(progress, open(tmp, "w"), indent=2)
    tmp.replace(pp)
    log(f"  wrote {pp}")

    sp = model_dir / "run_summary.json"
    prev_sum = {}
    if sp.exists():
        try:
            prev_sum = json.load(open(sp))
        except Exception:
            prev_sum = {}
    prev_sum.update({
        "rebuilt_from_disk_at": datetime.now().isoformat(),
        "total_images": total,
        "completed_shards": len(info),
        "per_worker_images": per_worker,
        "embedding_dim": sorted(dims)[0] if dims else None,
        "dtype": "float32",
        "normalised": True,
    })
    tmp = sp.with_suffix(".json.tmp")
    json.dump(prev_sum, open(tmp, "w"), indent=2)
    tmp.replace(sp)
    log(f"  wrote {sp}")
    return 0


def cmd_compare(embed_root: Path, workers: int) -> int:
    models = sorted(d for d in embed_root.iterdir()
                    if d.is_dir() and any(d.glob("worker_*/*.npy")))
    log(f"models: {[m.name for m in models]}")

    info = {}
    for m in models:
        info[m.name] = scan_model(m, workers)
        tot = sum(n for n, _ in info[m.name].values() if n > 0)
        log(f"  {m.name:<30} {len(info[m.name]):5d} shards  {tot:>10,} vectors")

    sets = {k: set(v) for k, v in info.items()}
    common = set.intersection(*sets.values()) if sets else set()
    log(f"\n  shards common to ALL models: {len(common)}")
    for k, s in sets.items():
        log(f"    {k:<30} extra={len(s - common):5d}  missing_vs_common=0")

    # For the shared shards, do row counts agree everywhere?
    log("\n  row-count agreement over the common shards:")
    disagree = []
    for k in sorted(common):
        counts = {m: info[m][k][0] for m in info}
        if len(set(counts.values())) != 1:
            disagree.append((k, counts))
    common_rows = sum(next(iter(info.values()))[k][0] for k in common)
    if disagree:
        log(f"    MISMATCH on {len(disagree)} shards, e.g.:")
        for k, c in disagree[:5]:
            log(f"      {k}: {c}")
    else:
        log(f"    identical on all {len(common)} shards")
        log(f"    shared corpus = {common_rows:,} images")
    return 1 if disagree else 0


def main():
    ap = argparse.ArgumentParser(description="Rebuild ledgers / verify shared corpus.")
    ap.add_argument("--rebuild", type=str, default=None,
                    help="Path to one model's embedding dir.")
    ap.add_argument("--compare", action="store_true",
                    help="Compare shard sets and row counts across all models.")
    ap.add_argument("--embed-root", type=str, default=str(DEFAULT_EMBED_ROOT))
    ap.add_argument("--workers", type=int, default=32)
    args = ap.parse_args()

    if args.rebuild:
        return cmd_rebuild(Path(args.rebuild), args.workers)
    if args.compare:
        return cmd_compare(Path(args.embed_root), args.workers)
    ap.print_help()
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
